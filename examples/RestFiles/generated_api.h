inline bool route_path_id(const char* const path, const uint8_t route, uint8_t& id) {
  id = 0U;
  const bool valid = mado::check(path != nullptr) && mado::check(route <= kStaticAsset);
  if (!valid) {
    return false;
  }
  switch (route) {
    case kGetFile:
    case kPutFile:
    case kDeleteFile:
      return mado::parse_path_id(path, PSTR("/api/files/"), id);
    default:
      return false;
  }
}

